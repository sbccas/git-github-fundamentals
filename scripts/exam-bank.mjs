/**
 * Final exam question bank (Milestone 12c plan §3). The bank lives in exam-bank/questions.json, which git ignores:
 * the repository is public and the answers must never be in it (M12C-D6).
 *
 *   node scripts/exam-bank.mjs
 *
 * checks the bank (4 different options, one correct answer, at least 5 questions per unit) and writes, into exam-bank/:
 *   - question-bank-review.html  a printable review sheet with the correct answers marked (for the owner)
 *   - load-questions.sql         paste into the Supabase SQL Editor to load the bank (older questions are retired,
 *                                papers already started keep working)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'exam-bank');
const bank = JSON.parse(fs.readFileSync(path.join(DIR, 'questions.json'), 'utf8'));
const qs = bank.questions;

const problems = [];
qs.forEach((q, i) => {
  if (![1, 2, 3, 4, 5].includes(q.unit)) problems.push(`#${i + 1}: unit must be 1-5`);
  if (!q.q?.trim()) problems.push(`#${i + 1}: question text missing`);
  if (!Array.isArray(q.options) || q.options.length !== 4 || new Set(q.options).size !== 4) problems.push(`#${i + 1}: needs 4 different options`);
  if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer > 3) problems.push(`#${i + 1}: answer must be 0-3`);
});
for (const u of [1, 2, 3, 4, 5]) if (qs.filter((q) => q.unit === u).length < 5) problems.push(`unit ${u}: fewer than 5 questions`);
if (problems.length) {
  console.error(`✗ Question bank problems:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;
const UNIT = { 1: 'Introduction to Version Control', 2: 'Getting Started with Git', 3: 'Branching and Merging', 4: 'Advanced Git Commands', 5: 'Introduction to GitHub' };

// Review sheet
let n = 0;
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Final exam question bank — review</title>
<style>body{font:14px/1.45 system-ui,Segoe UI,sans-serif;margin:32px;color:#111}h1{font-size:22px;margin:0 0 4px}h2{font-size:17px;margin:26px 0 8px;border-bottom:2px solid #ddd;padding-bottom:4px}
.q{break-inside:avoid;margin:0 0 14px}.q p{margin:0 0 4px}.q ol{margin:0 0 4px;padding-left:22px;list-style:upper-alpha}.ok{font-weight:700;color:#0a7a3a}.ok::after{content:"  ✓ correct"}
.ex{color:#555;font-size:12.5px;margin:0}.meta{color:#666;margin:0 0 16px}</style></head><body>
<h1>Git &amp; GitHub Fundamentals — final exam question bank</h1>
<p class="meta">${qs.length} questions · ${[1, 2, 3, 4, 5].map((u) => `Unit ${u}: ${qs.filter((q) => q.unit === u).length}`).join(' · ')} · each student gets 5 per unit, shuffled. Confidential — do not share with students.</p>
${[1, 2, 3, 4, 5].map((u) => `<h2>Unit ${u} — ${UNIT[u]}</h2>${qs.filter((q) => q.unit === u).map((q) => `
<div class="q"><p><b>${++n}.</b> ${esc(q.q)}</p><ol>${q.options.map((o, i) => `<li${i === q.answer ? ' class="ok"' : ''}>${esc(o)}</li>`).join('')}</ol>${q.explain ? `<p class="ex">${esc(q.explain)}</p>` : ''}</div>`).join('')}`).join('')}
</body></html>`;
fs.writeFileSync(path.join(DIR, 'question-bank-review.html'), html);

// Load script for the SQL Editor
const rows = qs.map((q) => `  (${q.unit}, ${sql(q.q)}, ${sql(JSON.stringify(q.options))}::jsonb, ${q.answer}, ${q.explain ? sql(q.explain) : 'null'})`);
fs.writeFileSync(path.join(DIR, 'load-questions.sql'), `-- Final exam question bank — generated by scripts/exam-bank.mjs on ${new Date().toISOString().slice(0, 10)}.
-- CONFIDENTIAL: contains the answers. Paste into the Supabase SQL Editor and Run. Never commit or share.
-- Earlier questions are retired (kept for papers already started); the new ones become active.
begin;
update private.exam_questions set active = false where active;
insert into private.exam_questions (unit, question, options, correct, explanation) values
${rows.join(',\n')};
commit;
select unit, count(*) as active_questions from private.exam_questions where active group by unit order by unit;
`);
console.log(`✓ ${qs.length} questions checked → exam-bank/question-bank-review.html and exam-bank/load-questions.sql`);
